"""Regenerate the hash-locked requirement files in packaging/.

    python3 -I packaging/update-lock.py                                   # newest versions pyproject.toml allows
    python3 -I packaging/update-lock.py rns==1.5.6 lxmf==1.2.0 ...        # these pins (the rest: newest)
    python3 -I packaging/update-lock.py --build pyinstaller==6.22.3 ...   # the build locks (see below)

requirements.lock lists every package rnfs needs at runtime (rns, lxmf and theirs) with the sha256 of every
file PyPI has for that version (all wheels and the sdist), so `pip install --require-hashes -r
requirements.lock` works on any platform and installs nothing else. install.sh, build-deb.sh, the PyInstaller
builds, the tests and (through flatpak/generate-sources.py) the Flatpak all install from it. Pin the versions
the tests ran with, run `python3 packaging/flatpak/generate-sources.py` afterwards and commit both.

With --build it writes the two build locks instead, hashed the same way:
  build-backend.lock  just the build backend (setuptools), for `pip wheel --no-build-isolation` in install.sh,
                      build-deb.sh and the tests. Its version must satisfy pyproject.toml's
                      [build-system] requires (this script checks); raise that bound when updating it.
  build-tools.lock    what the workflows build, check and lint with: build, twine, PyInstaller, setuptools,
                      ruff and their dependencies, for Linux and Windows (platform-only dependencies carry a
                      sys_platform marker). Packages also in requirements.lock are pinned to its versions, so
                      both locks can go into one environment (the PyInstaller one).

Needs pip >= 23 and network access.
"""
import json
import os
import re
import subprocess
import sys
import tempfile
import tomllib
import urllib.request

from pip._vendor.packaging.requirements import Requirement
from pip._vendor.packaging.utils import canonicalize_name

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
LOCK = os.path.join(HERE, "requirements.lock")
BACKEND_LOCK = os.path.join(HERE, "build-backend.lock")
TOOLS_LOCK = os.path.join(HERE, "build-tools.lock")
# The dependency tree has no platform markers that matter on CPython, so one platform resolves it all
RESOLVE_ARGS = ["--only-binary=:all:", "--implementation", "cp", "--python-version", "3.11",
                "--platform", "manylinux_2_28_x86_64", "--platform", "manylinux_2_17_x86_64"]
HEADER = """\
# rnfs's runtime dependencies, pinned to the versions it was tested with, with the sha256 of every file PyPI
# has for each (all platforms). Generated by packaging/update-lock.py; don't edit by hand:
#   python3 -I packaging/update-lock.py {pins}
# Install with: pip install --require-hashes -r packaging/requirements.lock
"""

# The build tools, resolved on this machine (pip evaluates environment markers for the running Python, so run
# it on Linux with Python 3.12, the release workflow's), then completed with the dependencies other
# platforms' markers select. Every file must have a wheel for each of these environments.
BUILD_TOOLS = ["setuptools", "build", "twine", "pyinstaller", "ruff"]
BUILD_PLATFORMS = {  # sys_platform: (marker values, wheel platform tags accepted)
    "linux": ({"os_name": "posix", "platform_system": "Linux", "platform_machine": "x86_64"},
              ("manylinux", "linux_x86_64")),
    "win32": ({"os_name": "nt", "platform_system": "Windows", "platform_machine": "AMD64"}, ("win_amd64",)),
}
BUILD_PYTHONS = ["3.11", "3.12", "3.13"]
BUILD_RESOLVE_ARGS = ["--only-binary=:all:", "--implementation", "cp", "--python-version", "3.12",
                      "--platform", "manylinux_2_28_x86_64", "--platform", "manylinux_2_17_x86_64",
                      "--platform", "manylinux2014_x86_64"]
BACKEND_HEADER = """\
# rnfs's build backend (setuptools), with the sha256 of every file PyPI has for it. Generated by
# packaging/update-lock.py; don't edit by hand:
#   python3 -I packaging/update-lock.py --build {pins}
# Install with: pip install --require-hashes --only-binary=:all: -r packaging/build-backend.lock
# then build with: pip wheel --no-build-isolation --no-deps .
"""
TOOLS_HEADER = """\
# The tools the workflows build, check and lint with (build, twine, PyInstaller, setuptools, ruff) and their
# dependencies, for CPython {pythons} on Linux x86_64 and Windows x64, with the sha256 of every
# file PyPI has for each. Generated by packaging/update-lock.py; don't edit by hand:
#   python3 -I packaging/update-lock.py --build {pins}
# Install with: pip install --require-hashes --only-binary=:all: -r packaging/build-tools.lock
"""


def requirements() -> list[str]:
    """project.dependencies from pyproject.toml."""
    with open(os.path.join(REPO, "pyproject.toml"), "rb") as f:
        return list(tomllib.load(f)["project"].get("dependencies", []))


def resolve_report(reqs: list[str], pins: list[str], args: list[str]) -> list[dict]:
    """pip's installation report items for reqs, with pins as constraints."""
    with tempfile.TemporaryDirectory() as tmp:
        constraints = os.path.join(tmp, "constraints.txt")
        with open(constraints, "w", encoding="utf-8") as f:
            f.write("".join(pin + "\n" for pin in pins))
        report = os.path.join(tmp, "report.json")
        subprocess.run(
            [sys.executable, "-I", "-m", "pip", "install", "--quiet", "--disable-pip-version-check", "--dry-run",
             "--ignore-installed", "--report", report, "--target", os.path.join(tmp, "target"),
             "-c", constraints, *args, *reqs],
            check=True, cwd=tmp)
        with open(report, encoding="utf-8") as f:
            return json.load(f)["install"]


def resolve(reqs: list[str], pins: list[str]) -> list[tuple[str, str]]:
    """[(name, version)] of everything pip installs for reqs, with pins as constraints."""
    items = resolve_report(reqs, pins, RESOLVE_ARGS)
    return sorted((item["metadata"]["name"].lower(), item["metadata"]["version"]) for item in items)


def release_files(name: str, version: str) -> list[dict]:
    """PyPI's (non-yanked) files for name==version."""
    with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=60) as response:
        release = json.load(response)
    files = [f for f in release["urls"] if not f.get("yanked")]
    if not files:
        raise SystemExit(f"update-lock.py: PyPI has no files for {name}=={version}")
    return files


def file_hashes(name: str, version: str) -> list[str]:
    """The sha256 of every file PyPI has for name==version, sorted."""
    return sorted({f["digests"]["sha256"] for f in release_files(name, version)})


def lock_entry(name: str, version: str, hashes: list[str], marker: str = "") -> str:
    """One requirement with its hashes, in requirements-file syntax."""
    return (f"{name}=={version}{marker} \\\n" + " \\\n".join(f"    --hash=sha256:{h}" for h in hashes) + "\n")


def write_runtime_lock(pins: list[str]) -> None:
    """Resolve, hash and write requirements.lock."""
    lines = [HEADER.format(pins=" ".join(pins)).replace(" \n", "\n")]
    for name, version in resolve(requirements(), pins):
        hashes = file_hashes(name, version)
        lines.append(lock_entry(name, version, hashes))
        print(f"{name}=={version}: {len(hashes)} files")
    with open(LOCK, "w", encoding="utf-8") as f:
        f.write("".join(lines))
    print(f"wrote {LOCK}")


def runtime_pins() -> list[str]:
    """name==version for every package requirements.lock pins."""
    with open(LOCK, encoding="utf-8") as f:
        return re.findall(r"(?m)^([A-Za-z0-9_.-]+==[^ \;]+)", f.read())


def marker_environment(platform: str, python: str) -> dict[str, str]:
    """PEP 508 marker values for CPython `python` on `platform`."""
    values, _ = BUILD_PLATFORMS[platform]
    return {"implementation_name": "cpython", "implementation_version": python + ".0",
            "platform_python_implementation": "CPython", "platform_release": "", "platform_version": "",
            "python_version": python, "python_full_version": python + ".0", "sys_platform": platform,
            "extra": "", **values}


def needed(roots: list[str], metadata: dict[str, list[str]], env: dict[str, str]) -> set[str]:
    """The packages (canonical names) that installing roots pulls in under env, following requires_dist."""
    found: set[str] = set()
    seen: set[tuple[str, frozenset[str]]] = set()
    queue = [(Requirement(r), {""}) for r in roots]
    while queue:
        req, extras = queue.pop()
        if req.marker and not any(req.marker.evaluate({**env, "extra": e}) for e in extras):
            continue
        name = canonicalize_name(req.name)
        if (name, frozenset(req.extras)) in seen:
            continue
        seen.add((name, frozenset(req.extras)))
        found.add(name)
        if name not in metadata:
            raise KeyError(name)
        for dep in metadata[name]:
            queue.append((Requirement(dep), {""} | set(req.extras)))
    return found


def env_marker(name: str, envs: set[tuple[str, str]]) -> str:
    """The marker (with its " ; ") that selects exactly envs, a set of (platform, python), or ""."""
    platforms = sorted({p for p, _ in envs})
    pythons = sorted({py for _, py in envs}, key=lambda v: tuple(map(int, v.split("."))))
    if envs != {(p, py) for p in platforms for py in pythons}:
        raise SystemExit(f"update-lock.py: can't write a marker for {name}'s environments {sorted(envs)}")
    parts = []
    if len(platforms) == 1 and len(BUILD_PLATFORMS) > 1:
        parts.append(f'sys_platform == "{platforms[0]}"')
    if pythons != BUILD_PYTHONS:
        if pythons == BUILD_PYTHONS[:len(pythons)]:
            parts.append(f'python_version < "{BUILD_PYTHONS[len(pythons)]}"')
        elif pythons == BUILD_PYTHONS[-len(pythons):]:
            parts.append(f'python_version >= "{pythons[0]}"')
        else:
            raise SystemExit(f"update-lock.py: can't write a marker for {name}'s Pythons {pythons}")
    return " ; " + " and ".join(parts) if parts else ""


def wheel_fits(filename: str, platform: str, python: str) -> bool:
    """A wheel file name's tags include one CPython `python` on `platform` can install."""
    if not filename.endswith(".whl"):
        return False
    pythons, abis, platforms = filename[:-4].split("-")[-3:]
    _, accepted = BUILD_PLATFORMS[platform]
    if not any(p == "any" or p.startswith(accepted) for p in platforms.split(".")):
        return False
    nodot = python.replace(".", "")
    for tag in pythons.split("."):
        if tag in ("py3", f"py{nodot}") or tag == f"cp{nodot}":
            return True
        if tag.startswith("cp3") and "abi3" in abis.split(".") and int(tag[3:]) <= int(nodot[1:]):
            return True
    return False


def write_build_locks(pins: list[str]) -> None:
    """Resolve, hash and write build-backend.lock and build-tools.lock."""
    if sys.version_info[:2] != (3, 12) or not sys.platform.startswith("linux"):
        raise SystemExit("update-lock.py --build: run it with Python 3.12 on Linux (pip evaluates markers for "
                         "the running Python)")
    constraints = runtime_pins() + pins
    extra: list[str] = []
    while True:  # resolve, then add what other platforms' markers select, until nothing is missing
        items = resolve_report(BUILD_TOOLS + extra, constraints, BUILD_RESOLVE_ARGS)
        versions = {canonicalize_name(i["metadata"]["name"]): i["metadata"]["version"] for i in items}
        metadata = {canonicalize_name(i["metadata"]["name"]): i["metadata"].get("requires_dist", []) for i in items}
        missing = []
        for platform in BUILD_PLATFORMS:
            for python in BUILD_PYTHONS:
                env = marker_environment(platform, python)
                for deps in metadata.values():
                    for dep in deps:
                        req = Requirement(dep)
                        if canonicalize_name(req.name) in versions:
                            continue
                        if req.marker is None or req.marker.evaluate({**env, "extra": ""}):
                            missing.append(f"{req.name}{req.specifier}")
        # (dependencies only an extra selects are left out: none of the roots asks for one)
        if not missing:
            break
        if set(missing) <= set(extra):
            raise SystemExit(f"update-lock.py: can't resolve {missing}")
        extra = sorted(set(extra) | set(missing))
    needs = {(p, py): needed(BUILD_TOOLS, metadata, marker_environment(p, py))
             for p in BUILD_PLATFORMS for py in BUILD_PYTHONS}

    setuptools = versions["setuptools"]
    with open(os.path.join(REPO, "pyproject.toml"), "rb") as f:
        backend = [Requirement(r) for r in tomllib.load(f)["build-system"]["requires"]]
    for req in backend:
        if canonicalize_name(req.name) != "setuptools":
            raise SystemExit(f"update-lock.py: unexpected build requirement {req} in pyproject.toml")
        if not req.specifier.contains(setuptools) or not any(s.operator == "<" for s in req.specifier):
            raise SystemExit(f"update-lock.py: setuptools {setuptools} isn't within pyproject.toml's "
                             f"build-system requires ({req}), or that has no upper bound: test it, then "
                             "change the bound")
    if metadata["setuptools"] and any(Requirement(d).marker is None for d in metadata["setuptools"]):
        raise SystemExit("update-lock.py: setuptools has dependencies now; build-backend.lock must list them")

    header_pins = " ".join(pins)
    backend_hashes = file_hashes("setuptools", setuptools)
    with open(BACKEND_LOCK, "w", encoding="utf-8") as f:
        f.write(BACKEND_HEADER.format(pins=header_pins).replace(" \n", "\n")
                + lock_entry("setuptools", setuptools, backend_hashes))
    print(f"wrote {BACKEND_LOCK}")

    lines = [TOOLS_HEADER.format(pins=header_pins, pythons=", ".join(BUILD_PYTHONS)).replace(" \n", "\n")]
    for name in sorted(versions):
        envs = {key for key, names in needs.items() if name in names}
        if not envs:
            continue
        marker = env_marker(name, envs)
        files = release_files(name, versions[name])
        for platform, python in envs:
            if not any(wheel_fits(f["filename"], platform, python) for f in files):
                raise SystemExit(f"update-lock.py: {name}=={versions[name]} has no wheel for CPython {python} "
                                 f"on {platform}")
        hashes = sorted({f["digests"]["sha256"] for f in files})
        lines.append(lock_entry(name, versions[name], hashes, marker))
        print(f"{name}=={versions[name]}{marker}: {len(hashes)} files")
    with open(TOOLS_LOCK, "w", encoding="utf-8") as f:
        f.write("".join(lines))
    print(f"wrote {TOOLS_LOCK}")


def main() -> None:
    """Write requirements.lock, or with --build the build locks."""
    args = sys.argv[1:]
    if args[:1] == ["--build"]:
        write_build_locks(args[1:])
    else:
        write_runtime_lock(args)


if __name__ == "__main__":
    main()
