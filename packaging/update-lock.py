"""Regenerate packaging/requirements.lock: rnfs's runtime dependencies at exact versions, with hashes.

    python3 -I packaging/update-lock.py                                   # newest versions pyproject.toml allows
    python3 -I packaging/update-lock.py rns==1.5.6 lxmf==1.2.0 ...        # these pins (the rest: newest)

The lock lists every package rnfs needs at runtime (rns, lxmf and theirs) with the sha256 of every file PyPI
has for that version (all wheels and the sdist), so `pip install --require-hashes -r requirements.lock` works
on any platform and installs nothing else. install.sh, build-deb.sh, the PyInstaller builds and (through
flatpak/generate-sources.py) the Flatpak all install from it. Pin the versions the tests ran with, run
`python3 packaging/flatpak/generate-sources.py` afterwards and commit both. Needs pip >= 23 and network access.
"""
import json
import os
import subprocess
import sys
import tempfile
import tomllib
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
LOCK = os.path.join(HERE, "requirements.lock")
# The dependency tree has no platform markers that matter on CPython, so one platform resolves it all
RESOLVE_ARGS = ["--only-binary=:all:", "--implementation", "cp", "--python-version", "3.11",
                "--platform", "manylinux_2_28_x86_64", "--platform", "manylinux_2_17_x86_64"]
HEADER = """\
# rnfs's runtime dependencies, pinned to the versions it was tested with, with the sha256 of every file PyPI
# has for each (all platforms). Generated by packaging/update-lock.py; don't edit by hand:
#   python3 -I packaging/update-lock.py {pins}
# Install with: pip install --require-hashes -r packaging/requirements.lock
"""


def requirements() -> list[str]:
    """project.dependencies from pyproject.toml."""
    with open(os.path.join(REPO, "pyproject.toml"), "rb") as f:
        return list(tomllib.load(f)["project"].get("dependencies", []))


def resolve(reqs: list[str], pins: list[str]) -> list[tuple[str, str]]:
    """[(name, version)] of everything pip installs for reqs, with pins as constraints."""
    with tempfile.TemporaryDirectory() as tmp:
        constraints = os.path.join(tmp, "constraints.txt")
        with open(constraints, "w", encoding="utf-8") as f:
            f.write("".join(pin + "\n" for pin in pins))
        report = os.path.join(tmp, "report.json")
        subprocess.run(
            [sys.executable, "-I", "-m", "pip", "install", "--quiet", "--disable-pip-version-check", "--dry-run",
             "--ignore-installed", "--report", report, "--target", os.path.join(tmp, "target"),
             "-c", constraints, *RESOLVE_ARGS, *reqs],
            check=True, cwd=tmp)
        with open(report, encoding="utf-8") as f:
            items = json.load(f)["install"]
    return sorted((item["metadata"]["name"].lower(), item["metadata"]["version"]) for item in items)


def file_hashes(name: str, version: str) -> list[str]:
    """The sha256 of every file PyPI has for name==version, sorted."""
    with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=60) as response:
        release = json.load(response)
    hashes = sorted({f["digests"]["sha256"] for f in release["urls"] if not f.get("yanked")})
    if not hashes:
        raise SystemExit(f"update-lock.py: PyPI has no files for {name}=={version}")
    return hashes


def main() -> None:
    """Resolve, hash and write requirements.lock."""
    pins = sys.argv[1:]
    lines = [HEADER.format(pins=" ".join(pins)).replace(" \n", "\n")]
    for name, version in resolve(requirements(), pins):
        hashes = file_hashes(name, version)
        lines.append(f"{name}=={version} \\\n" + " \\\n".join(f"    --hash=sha256:{h}" for h in hashes) + "\n")
        print(f"{name}=={version}: {len(hashes)} files")
    with open(LOCK, "w", encoding="utf-8") as f:
        f.write("".join(lines))
    print(f"wrote {LOCK}")


if __name__ == "__main__":
    main()
